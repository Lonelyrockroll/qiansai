"""Generate a bright, decaying 32-partial struck-string demonstration voice."""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SAMPLE_RATE = 50_000_000 / 1024
HARMONICS = 32
# Keep the upper partials resolvable during a short FFT window. This is a
# separate demonstration patch; the v26 piano keeps its original tuning.
STIFFNESS = (0.000008, 0.000010, 0.000012, 0.000015, 0.000018, 0.000022)
FUNDAMENTAL_DECAY = (2.5, 2.2, 2.0, 1.7, 1.45, 1.2)
HARD_GAIN_BUDGET = 24_000


def decay_shifts(seconds):
    """Represent fractional amplitude loss by two shift-and-add terms."""
    target = 1 - math.exp(-1 / (SAMPLE_RATE * seconds))
    return min(((a, b) for a in range(10, 23) for b in range(a, 32)),
               key=lambda shifts: abs(2.0**-shifts[0] + 2.0**-shifts[1] - target))


def parameters():
    # Pluck-like spectral falloff, without deliberately disappearing even/odd partials.
    weights = [(1 + 0.22*i)**-1.15 for i in range(HARMONICS)]
    scale = HARD_GAIN_BUDGET / sum(weights)
    hard = [round(w * scale) for w in weights]
    hard[0] += HARD_GAIN_BUDGET - sum(hard)
    for band, stiffness in enumerate(STIFFNESS):
        for index in range(HARMONICS):
            n = index + 1
            ratio = n * math.sqrt((1 + stiffness*n*n)/(1 + stiffness))
            soft = round(hard[index] * (0.82 - 0.12*index/(HARMONICS-1)))
            first, second = decay_shifts(FUNDAMENTAL_DECAY[band] / (1 + 0.035*index))
            # Deterministic quadratic phase spreads the initial sample peaks.
            phase = (4096*n*(n-1)//(2*HARMONICS)) % 4096
            yield band, index, (round(ratio * 65536), soft, hard[index], first, second, phase)


def generate():
    lines = [
        '// Generated by generate_coeffs.py. 32 nonzero additive components in each register.',
        '// Packed MSB first: Q16 ratio (22), soft/hard gains (16 each), shifts (5 each), phase (12).',
        'module modal32_coeffs(input wire [2:0] band, group, output wire [75:0] c0,c1,c2,c3);',
        ' function [75:0] coeff(input [7:0] address);',
        ' begin case(address)',
    ]
    for band, index, fields in parameters():
        value = 0
        for field, width in zip(fields, (22, 16, 16, 5, 5, 12)):
            if not 0 <= field < (1 << width):
                raise ValueError((band, index, field, width))
            value = (value << width) | field
        lines.append(f"  8'd{32*band+index}: coeff=76'h{value:019x};")
    lines += [
        "  default: coeff=76'd0;",
        ' endcase end endfunction',
        " assign c0=coeff({band,group,2'd0});",
        " assign c1=coeff({band,group,2'd1});",
        " assign c2=coeff({band,group,2'd2});",
        " assign c3=coeff({band,group,2'd3});",
        'endmodule',
    ]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    (ROOT/'modal32_coeffs.v').write_text(generate(), encoding='ascii')
