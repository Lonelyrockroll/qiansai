"""Generate a 32-partial piano using the approved v26 piano as its tonal reference."""
import cmath
import functools
import math
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[3]
LEGACY = PROJECT / 'control_key_gain/piano_modal_tables_compact.v'
FS = 50_000_000 / 1024
STIFFNESS = (.00025, .00013, .00010, .00018, .0004, .0010)
FIELD_WIDTHS = (22, 16, 16, 5, 5, 12)
HARD_BUDGET = 28000


def legacy_bands():
    lookup = {}
    for number, digits in re.findall(r"7'd(\d+): coeff=74'h([a-fA-F0-9]+)", LEGACY.read_text()):
        word = int(digits, 16)
        fields = []
        for bits in (12, 5, 5, 16, 16, 20):
            fields.append(word & ((1 << bits)-1))
            word >>= bits
        lookup[int(number)] = tuple(reversed(fields))
    if set(lookup) != set(range(96)):
        raise ValueError('Expected six complete bands of the original 16-mode piano')
    return [[lookup[16*b+i] for i in range(16)] for b in range(6)]


def decay_time(a, b):
    return -1 / (FS * math.log1p(-(2**-a + 2**-b)))


@functools.lru_cache(maxsize=None)
def shifts(seconds):
    loss = -math.expm1(-1/(seconds * FS))
    return min(((a, b) for a in range(10, 23) for b in range(a, 32)),
               key=lambda s: abs(2**-s[0] + 2**-s[1] - loss))


def generate_bands():
    bands = []
    for band, old in enumerate(legacy_bands()):
        body = list(old[:12])
        for i in range(4):
            ratio, soft, hard, a, b, phase = body[i]
            _, cs, ch, ca, cb, cp = old[12+i]
            # Fold the starting amplitudes and phases of the old near-unison strings
            # into each body partial. The slower decay keeps some sustain; this
            # single partial cannot reproduce the old two-string beating.
            first = cmath.rect(hard, math.tau * phase / 4096)
            other = cmath.rect(ch, math.tau * cp / 4096)
            angle = round(cmath.phase(first + other) * 4096 / math.tau) % 4096
            fraction = ch / (hard + ch)
            tau = decay_time(a, b) * (decay_time(ca, cb) / decay_time(a, b))**(1.35 * fraction)
            qa, qb = shifts(tau)
            body[i] = (ratio, soft+cs, round(abs(first+other)), qa, qb, angle)

        for n in range(13, 33):
            t = (n-13)/19
            # Highs are a short strike whose energy drops quickly after onset.
            # A mild hammer-position notch avoids a perfectly smooth bright shelf.
            strike = 1 - .14 * math.cos(math.tau * (n-1) / 7)**2
            hard = round((174-48*t) * strike)
            soft = round((70-13*t) * strike)
            seconds = (.155-.050*t) * (1.2, 1.1, 1., .9, .8, .72)[band]
            qa, qb = shifts(seconds)
            effective_n = 12 + .45*(n-12)
            ratio = n * math.sqrt((1+STIFFNESS[band]*effective_n**2)/(1+STIFFNESS[band]))
            phase = (4096*n*(n-1)//64 + 407) % 4096
            body.append((round(ratio*65536), soft, hard, qa, qb, phase))

        # v26's legacy mixing budget is preserved even for the strongest strike.
        scale = HARD_BUDGET/sum(row[2] for row in body)
        rows = [(r, round(s*scale), round(h*scale), a, b, p) for r,s,h,a,b,p in body]
        r, s, h, a, b, p = rows[0]
        rows[0] = (r, s, h+HARD_BUDGET-sum(row[2] for row in rows), a, b, p)
        bands.append(rows)
    return bands


def source():
    lines = ["// Musical piano. Generated by generate_musical.py from the shipped v26 piano.",
             "module modal32_coeffs(input wire [2:0] band, group, output wire [75:0] c0,c1,c2,c3);",
             " function [75:0] coeff(input [7:0] address);", " begin case(address)"]
    for band, rows in enumerate(generate_bands()):
        for i, row in enumerate(rows):
            word = 0
            for field, width in zip(row, FIELD_WIDTHS):
                if not 0 <= field < 1 << width:
                    raise ValueError((band, i, field))
                word = (word << width) | field
            lines.append(f"  8'd{32*band+i}: coeff=76'h{word:019x};")
    lines += ["  default: coeff=76'd0;", " endcase end endfunction"]
    lines += [f" assign c{i}=coeff({{band,group,2'd{i}}});" for i in range(4)]
    return '\n'.join(lines + ["endmodule", ""])


if __name__ == '__main__':
    (HERE/'modal32_coeffs.v').write_text(source(), encoding='ascii')
